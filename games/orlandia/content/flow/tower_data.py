# 层等级生成：1-10 层 Lv71-80 / 11-20 层 Lv81-90 / 21-30 层 Lv91-100
def _floor_lv(floor: int) -> int:
    if floor <= 10:
        return 70 + floor
    if floor <= 20:
        return 80 + (floor - 10)
    return 90 + (floor - 20)


